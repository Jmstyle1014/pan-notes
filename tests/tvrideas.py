import os,sys,json
from playwright.sync_api import sync_playwright
# Panyard VR 💡 Ideas: a pad (menu → 💡 Ideas) with a blank score that writes the notes you hit on the pans (the length
# you picked, two notes together as a chord, rests, undo, ▶ plays it back on the pans), a typing page with a keyboard on the
# pad, and a drawing page for the beam. Ideas are kept on the headset and listed on the page's Songs tab.
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.environ['WORK']+'/tvrideas/';os.makedirs(D,exist_ok=True)
fails=[]
def check(ok,what):
    print(('ok   ' if ok else 'FAIL ')+what)
    if not ok:fails.append(what)
def route(r):
    u=r.request.url.split('?')[0].replace('https://pan.test/','')
    f=os.path.join(ROOT,'source','band-sounds',u.split('/')[-1]) if u.startswith('band/band-sounds/') else os.path.join(ROOT,u if not u.endswith('/') else u+'index.html')
    return r.fulfill(path=f) if os.path.exists(f) else r.fulfill(status=404,body='')
with sync_playwright() as p:
    b=p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required','--use-gl=swiftshader','--enable-unsafe-swiftshader'])
    pg=b.new_page(viewport={'width':1280,'height':800});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.add_init_script("if(!sessionStorage.getItem('s')){localStorage.setItem('panyard-vr-welcomed','1');localStorage.setItem('panyard-vr-yard','0');sessionStorage.setItem('s','1')}")
    pg.route('https://pan.test/**',route)
    load=lambda:(pg.wait_for_function("window.VR&&VR.ready()>=79&&VR.drums()>0",timeout=90000),pg.evaluate("document.getElementById('hud').hidden=true"))
    pg.goto('https://pan.test/vr/');load()
    check('mideas' in pg.evaluate("VR.menuHits()"),'the menu has a 💡 Ideas button')
    pg.evaluate("VR.ideas.press('mideas')")
    check(pg.evaluate("VR.ideas.shown()") and pg.evaluate("VR.ideas.live()"),'it opens the pad, and the beam can press it')
    st=pg.evaluate("VR.ideas.state()");check(len(st['list'])==1 and st['list'][0]['title']=='Idea 1','a first, empty idea is ready')
    hit=lambda i:pg.evaluate(f"VR.players.hitCopy('tenor',0,'{i}',2.5)")
    notes=lambda:pg.evaluate("VR.ideas.state().list[0].notes")
    for i in ['tenor:60','tenor:62','tenor:64']:hit(i);pg.wait_for_timeout(150)
    n=notes();check([x['m'] for x in n]==[60,62,64] and [x['b'] for x in n]==[0,1,2],f'C4 D4 E4 hit on the pans are written as C4 D4 E4, a beat each {[(x["m"],x["b"]) for x in n]}')
    pg.evaluate("VR.ideas.press('ialen:0.5')");hit('tenor:65');pg.wait_for_timeout(150);hit('tenor:67');pg.wait_for_timeout(150)
    n=notes();check(n[-1]['d']==.5 and n[-1]['b']==3.5,'Eighth: the next notes are half a beat each')
    pg.evaluate("VR.ideas.press('ialen:2')");pg.evaluate("VR.players.hitCopy('tenor',0,'tenor:60',2.5);VR.players.hitCopy('tenor',0,'tenor:64',2.5)")
    n=notes();check(len(n)==7 and n[-1]['b']==n[-2]['b']==4 and n[-1]['d']==2,'two notes hit together stack as a chord (a half note)')
    pg.evaluate("VR.ideas.press('iarest')");n=notes();check(n[-1].get('rest') and n[-1]['b']==6,'Rest adds a rest after them')
    pg.evaluate("VR.ideas.press('iaundo')");pg.evaluate("VR.ideas.press('iaundo')");n=notes();check(len(n)==5,'⌫ Undo takes off the rest, then the whole chord')
    pg.evaluate("VR.ideas.press('iawrite')");hit('tenor:72');pg.wait_for_timeout(150);check(len(notes())==5,'with Writing off you can play without writing')
    pg.evaluate("VR.ideas.press('iawrite')");pg.evaluate("VR.ideas.press('ialen:1')")
    for i in ['tenor:72','tenor:71','tenor:69','tenor:67','tenor:65','tenor:64','tenor:62','tenor:60','tenor:62','tenor:64']:hit(i);pg.wait_for_timeout(120)
    pg.evaluate("VR.ideas.open(true);VR.ideas.noSticks()");pg.wait_for_timeout(500);pg.screenshot(path=D+'score.png')
    pg.evaluate("VR.hits.length=0;VR.ideas.press('iaplay')");pg.wait_for_timeout(300);check(pg.evaluate("VR.ideas.ia().playing"),'▶ Play plays the score')
    pg.wait_for_timeout(2500);played=pg.evaluate("VR.hits.filter(h=>h.p).map(h=>h.id)")
    check(played[:3]==['tenor:60','tenor:62','tenor:64'],f'on the pans, in order {played[:5]}')
    check(len(notes())==15,'playing back writes nothing new')
    pg.evaluate("VR.ideas.press('iaplay')");check(not pg.evaluate("VR.ideas.ia().playing"),'■ Stop stops it')
    for _ in range(30):hit('tenor:60');pg.wait_for_timeout(95)
    check(pg.evaluate("VR.ideas.ia().page")==1,'past bar 8 the score turns to the next page by itself')
    pg.evaluate("VR.ideas.press('iapg:-1')");check(pg.evaluate("VR.ideas.ia().page")==0,'◀ goes back to bars 1–8')
    # bass pans write on the bass clef: tested by drawing; just check a bass idea draws without errors
    pg.evaluate("VR.ideas.press('ianew')");pg.evaluate("VR.ideas.press('iatab:type')")
    check(len(pg.evaluate("VR.ideas.state().list"))==2,'＋ New starts a second idea')
    for k in ['c','space','⇧','g','space','⇧','a','m','⏎']:pg.evaluate(f"VR.ideas.press('iakey:{k}')")
    pg.evaluate("VR.ideas.type('verse two, the bass walks down')")
    t=pg.evaluate("VR.ideas.state().list[0].text");check(t=='C G Am\nVerse two, the bass walks down',f'the keyboard types (capitals after a new line) {t!r}')
    pg.evaluate("VR.ideas.press('iakey:⌫')");check(pg.evaluate("VR.ideas.state().list[0].text").endswith('dow'),'⌫ deletes a letter')
    pg.wait_for_timeout(300);pg.screenshot(path=D+'type.png')
    pg.evaluate("VR.ideas.press('iatab:draw')")
    pg.evaluate("VR.ideas.pen([[200,300],[260,340],[320,300],[380,340],[440,300]])")
    pg.evaluate("VR.ideas.press('iaink:1')");pg.evaluate("VR.ideas.beam(600,400,true);VR.ideas.beam(700,500);VR.ideas.beam(800,420);VR.ideas.beam(0,0,false)")
    ink=pg.evaluate("VR.ideas.state().list[0].ink");check(len(ink)==2 and len(ink[1]['p'])==3 and ink[1]['c']=='#f6ba45',f'the beam draws lines, in the colour picked ({len(ink)} lines)')
    pg.wait_for_timeout(300);pg.screenshot(path=D+'draw.png')
    pg.evaluate("VR.ideas.press('iainkundo')");check(len(pg.evaluate("VR.ideas.state().list[0].ink"))==1,'↶ Undo line takes the last line off')
    pg.evaluate("VR.ideas.press('iaclr')");check(len(pg.evaluate("VR.ideas.state().list[0].ink"))==1,'🗑 Clear asks first')
    pg.evaluate("VR.ideas.press('iaclr')");check(len(pg.evaluate("VR.ideas.state().list[0].ink"))==0,'and clears on the second press')
    pg.evaluate("VR.ideas.press('iaprev:1')");check(len(pg.evaluate("VR.ideas.state().list.find(e=>e.title=='Idea 1').notes"))==45,'▶ flips back to the first idea, its score kept')
    pg.evaluate("VR.ideas.press('iaclose')");check(not pg.evaluate("VR.ideas.shown()"),'✕ Close puts the pad away')
    hit('tenor:60');check(len(pg.evaluate("VR.ideas.state().list.find(e=>e.title=='Idea 1').notes"))==45,'with the pad away, playing writes nothing')
    pg.reload();load()
    st=pg.evaluate("VR.ideas.state()");check(len(st['list'])==2 and st['list'][0]['text'].startswith('C G Am'),'ideas are kept on the headset')
    pg.evaluate("document.getElementById('hud').hidden=false;hudShow('#ideaBox')");pg.wait_for_timeout(200)
    rows=pg.evaluate("document.querySelectorAll('#ideaBox .idea').length");check(rows==2,'the page\'s Songs tab lists the ideas')
    pg.fill('#ideaBox .idea textarea','Typed on the page');check(pg.evaluate("VR.ideas.state().list[0].text")=='Typed on the page','and you can type an idea\'s notes there with a real keyboard')
    pg.screenshot(path=D+'page.png')
    check(not errs,f'no page errors {errs[:3]}')
    b.close()
print('FAILED: '+str(len(fails)) if fails else 'ALL OK');sys.exit(1 if fails else 0)
